"""Symplectic-corrector coefficients of ``ferroastro-symplectic`` (NUM-004, WP29): derive, emit.

Derivation (IMPLEMENTATION-NOTES WP29; no corrector table or integrator source was consulted,
DEP-008). For the Wisdom-Holman map ``W = e^{hA/2} e^{eps h B} e^{hA/2}``,
``log W = hA + eps h phi(x) B + O(eps^2)`` with ``x = h ad_A`` and
``phi(x) = (x/2) / sinh(x/2)``. The transformation ``e^{eps chi}`` with
``chi = h (phi(x) - 1)/x B`` conjugates ``W`` to the exact flow up to ``O(eps^2)``. The products
``X(a, b) X(-a, -b)``, ``X(a, b) = e^{aA} e^{b eps B} e^{-aA}``, equal
``exp(2 eps b sinh(a ad_A) B + O(eps^2))``. With ``a_i = i h`` and ``b_i = beta_i h``
(``i = 1 .. n``), the odd Taylor coefficients of ``chi`` up to ``x^{2n-1}`` are matched when

    sum_i 2 beta_i i^{2k+1} / (2k+1)! = d_k,   k = 0 .. n-1,

where ``(phi(x) - 1)/x = sum_k d_k x^{2k+1}``. From ``y/sinh(y) = sum_m (2 - 2^{2m}) B_{2m}
y^{2m}/(2m)!`` (Bernoulli numbers ``B_{2m}``), ``d_k = (2 - 2^{2m}) B_{2m} / (2^{2m} (2m)!)``
with ``m = k + 1``; ``d_0 = -1/24``. ``n = 1, 2, 3, 5`` give correctors of order 3, 5, 7, 11.
Every number is an exact rational, and each numerator and denominator fits in 53 bits, so the
Rust table holds them as integers.

Usage::

    uv run python symplectic_correctors.py           # print the table
    uv run python symplectic_correctors.py --check   # fail if the committed Rust table differs
"""

from __future__ import annotations

import argparse
import sys
from fractions import Fraction
from math import comb, factorial
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TABLE = ROOT / "crates" / "ferroastro-symplectic" / "src" / "corrector_table.rs"
#: Corrector order -> number of stage pairs n.
ORDERS: dict[int, int] = {3: 1, 5: 2, 7: 3, 11: 5}


def bernoulli(n: int) -> list[Fraction]:
    """Bernoulli numbers ``B_0 .. B_n`` (``B_1 = -1/2``) by the standard recurrence."""
    b = [Fraction(0)] * (n + 1)
    b[0] = Fraction(1)
    for m in range(1, n + 1):
        b[m] = -sum((comb(m + 1, k) * b[k] for k in range(m)), Fraction(0)) / (m + 1)
    return b


def d_coefficient(k: int) -> Fraction:
    """Coefficient of ``x^{2k+1}`` in ``(phi(x) - 1)/x``."""
    m = k + 1
    b2m = bernoulli(2 * m)[2 * m]
    num: Fraction = (2 - 2 ** (2 * m)) * b2m
    den = Fraction(2 ** (2 * m) * factorial(2 * m))
    return num / den


def solve(n: int) -> list[Fraction]:
    """``beta_1 .. beta_n`` of the order-(2n+1) corrector (exact Gauss-Jordan)."""
    rows = [
        [Fraction(2 * i ** (2 * k + 1), factorial(2 * k + 1)) for i in range(1, n + 1)]
        + [d_coefficient(k)]
        for k in range(n)
    ]
    for c in range(n):
        p = next(r for r in range(c, n) if rows[r][c] != 0)
        rows[c], rows[p] = rows[p], rows[c]
        for r in range(n):
            if r != c:
                f = rows[r][c] / rows[c][c]
                rows[r] = [a - f * b for a, b in zip(rows[r], rows[c], strict=True)]
    return [rows[i][n] / rows[i][i] for i in range(n)]


def residual(n: int, beta: list[Fraction]) -> Fraction:
    """Largest exact residual of the matching conditions (0 for a correct solution)."""
    worst = Fraction(0)
    for k in range(n):
        s = sum(
            (
                Fraction(2 * (i + 1) ** (2 * k + 1), factorial(2 * k + 1)) * b
                for i, b in enumerate(beta)
            ),
            Fraction(0),
        )
        worst = max(worst, abs(s - d_coefficient(k)))
    return worst


def render() -> str:
    """Render the Rust table."""
    lines = [
        "// SPDX-FileCopyrightText: 2026 Proper-Time Physics Institute",
        "// SPDX-License-Identifier: Apache-2.0",
        "//! Generated by `tools/symplectic_correctors.py` (do not edit): the exact rational",
        "//! symplectic-corrector coefficients `beta_i` (stage `i` at `a_i = i h`), as",
        "//! `(numerator, denominator)`.",
        "",
    ]
    for order, n in ORDERS.items():
        beta = solve(n)
        if residual(n, beta) != 0:
            raise ValueError(f"order {order}: non-zero residual")
        for b in beta:
            if max(abs(b.numerator), b.denominator) >= 2**53:
                raise ValueError(f"order {order}: {b} does not fit in 53 bits")
        body = ", ".join(f"({b.numerator}, {b.denominator})" for b in beta)
        lines.append(f"/// Order {order} ({n} stage pair{'s' if n > 1 else ''}).")
        lines.append(f"pub(crate) const ORDER_{order}: [(i64, i64); {n}] = [{body}];")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    """Entry point."""
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="fail if the committed table differs")
    ap.add_argument("--write", action="store_true", help="(re)write the Rust table")
    args = ap.parse_args(argv)
    text = render()
    if args.write:
        TABLE.write_text(text, encoding="utf-8")
        print(f"wrote {TABLE}")
        return 0
    if args.check:
        if not TABLE.exists() or TABLE.read_text(encoding="utf-8") != text:
            print(f"{TABLE} is stale; run `uv run python symplectic_correctors.py --write`")
            return 1
        print("corrector table up to date")
        return 0
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
