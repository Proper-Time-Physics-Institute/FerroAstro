fn spec(file: &str) -> ScenarioSpec {
    let p = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../ci/scenarios")
        .join(file);
    let mut s = ScenarioSpec::parse(&std::fs::read_to_string(p).unwrap()).unwrap();
    s.span.years = 1.0;
    s.span.stop_after_passages = None;
    s
}

fn fingerprint(out: &RunOutput) -> String {
    let mut h = Sha256::new();
    let mut put = |z: f64| h.update(z.to_bits().to_le_bytes());
    let mut record = |s: &StateRecord| {
        s.t.iter().for_each(|&z| put(z));
        for xyz in s.positions.iter().chain(&s.velocities) {
            xyz.iter().flatten().for_each(|&z| put(z));
        }
    };
    out.states.iter().for_each(&mut record);
    if let Some(f) = &out.final_state {
        record(f);
    }
    for p in &out.passages {
        p.t.iter().for_each(|&z| put(z));
        p.r.iter().chain(&p.v).flatten().for_each(|&z| put(z));
    }
    h.update(out.model.as_bytes());
    h.update(
        format!(
            "{} states, {} passages",
            out.states.len(),
            out.passages.len()
        )
        .as_bytes(),
    );
    h.finalize()
        .iter()
        .fold(String::with_capacity(64), |mut s, b| {
            use std::fmt::Write as _;
            let _ = write!(s, "{b:02x}");
            s
        })
}

/// Verifies: PHY-020, CI-002
#[test]
fn scenarios_without_the_conformal_table_run_bit_for_bit_as_before() {
    if De440::load_cached_or_skip("scenarios_without_the_conformal_table_run_bit_for_bit_as_before")
        .unwrap()
        .is_none()
    {
        return;
    }
    let f = ferroastro_testdata::locate_product("de440-header").expect("cached header.440");
    let prov = f.provenance();
    let h = Header::parse(&std::fs::read_to_string(&f.path).unwrap()).unwrap();
    let data = DataSources::none().with_header(&h, &prov);
    let mut bad = Vec::new();
    for (file, want) in RECORDED {
        let s = spec(file);
        assert!(s.forces.conformal.is_none(), "{file}");
        let out = run(&s, &data).unwrap();
        assert!(
            !out.model.contains("comparison model"),
            "{file}: {}",
            out.model
        );
        println!("{file}: {}", out.model);
        let got = fingerprint(&out);
        println!("(\"{file}\", \"{got}\"),");
        if got != want {
            bad.push(file);
        }
    }
    assert!(bad.is_empty(), "changed: {bad:?}");
}
