//! Scenario digests are stable across spec extensions (CI-002, PHY-020 acceptance (d)).
//!
//! `tests/data/scenario-digests.toml` records [`ScenarioSpec::digest`] of every committed scenario
//! (`ci/scenarios/*.toml` and the REF-011 canaries `ci/oracles/canaries/*.toml`) as computed on
//! FerroAstro main before the optional `[forces.conformal]` table existed (ADR-0016, F1 branch
//! 18666f5). A new optional force table must be skipped when absent, so every recorded digest, and
//! with it every checkpoint and differential-run store keyed by it, stays byte-identical. The
//! file is written by hand from that run and never regenerated by the test.

#![expect(
    clippy::unwrap_used,
    reason = "test: a failed unwrap is a test failure"
)]

use ferroastro_scenario::ScenarioSpec;
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

fn root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn toml_files(dir: &Path) -> Vec<PathBuf> {
    let mut v: Vec<PathBuf> = std::fs::read_dir(dir)
        .unwrap()
        .map(|e| e.unwrap().path())
        .filter(|p| p.extension().is_some_and(|x| x == "toml"))
        .collect();
    v.sort();
    v
}

/// Every committed scenario's digest equals the one recorded before the conformal table was
/// added, and no committed scenario serialises a `conformal` key.
///
/// Verifies: CI-002, PHY-020
#[test]
fn committed_scenario_digests_are_unchanged() {
    let recorded: BTreeMap<String, String> = toml::from_str(
        &std::fs::read_to_string(
            PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/data/scenario-digests.toml"),
        )
        .unwrap(),
    )
    .unwrap();
    let mut seen = BTreeMap::new();
    for dir in ["ci/scenarios", "ci/oracles/canaries"] {
        for f in toml_files(&root().join(dir)) {
            let spec = ScenarioSpec::parse(&std::fs::read_to_string(&f).unwrap()).unwrap();
            let json = serde_json::to_string(&spec).unwrap();
            assert!(!json.contains("conformal"), "{}: {json}", f.display());
            let key = format!("{dir}/{}", f.file_name().unwrap().to_string_lossy());
            println!("\"{key}\" = \"{}\"", spec.digest());
            seen.insert(key, spec.digest());
        }
    }
    assert_eq!(
        seen.keys().collect::<Vec<_>>(),
        recorded.keys().collect::<Vec<_>>(),
        "the set of committed scenarios changed: record the new file's digest by hand"
    );
    for (k, d) in &seen {
        assert_eq!(Some(d), recorded.get(k), "digest of {k} changed");
    }
}
